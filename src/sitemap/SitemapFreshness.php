declare(strict_types=1);

namespace Besnovatyj\Contracts\sitemap;

/**
 * Необязательное расширение {@see SitemapProvider}: дешёвая проверка «изменилось ли что-нибудь».
 *
 * Нужно тяжёлым разделам — каталогу на десятки тысяч позиций, где полный обход при каждой сборке
 * стоит заметных секунд и нагрузки на базу. Модуль карты спрашивает отпечаток раздела и, если он не
 * изменился с прошлой сборки, переиспользует уже готовый файл, не читая ни одной записи.
 *
 * Реализовывать обязаны не все: без этого интерфейса раздел просто пересобирается всегда — для
 * сотен и тысяч записей это правильное умолчание, потому что оно не может «залипнуть».
 *
 * Отпечаток — НЕПРОЗРАЧНАЯ строка, а не дата, и это принципиально: «время последнего изменения»
 * (`MAX(updated_at)`) не замечает удаления записи, а удалённая страница обязана исчезнуть из карты.
 * Рабочая и дешёвая формула — количество плюс время последней правки, одним индексным запросом:
 *
 * ```php
 * $row = Post::find()->select(['n' => 'COUNT(*)', 'm' => 'MAX(updated_at)'])->asArray()->one();
 * return $row['n'] . ':' . $row['m'];
 * ```
 *
 * Требования к реализации: ДЁШЕВО (один запрос, без обхода записей) и ПОЛНО — отпечаток обязан
 * меняться при любой правке, влияющей на карту, включая удаление и смену slug. Если гарантировать
 * это нельзя — интерфейс лучше не реализовывать вовсе: молча устаревшая карта хуже, чем лишний
 * обход раз в сутки.
 */
interface SitemapFreshness
{
    /**
     * Отпечаток текущего состояния раздела.
     *
     * `null` — «не знаю»: раздел будет пересобран. Так же следует отвечать на неизвестный ключ.
     *
     * @param string $section ключ раздела из {@see SitemapSection::$key}
     */
    public function sitemapRevision(string $section): ?string;
}
