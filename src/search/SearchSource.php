declare(strict_types=1);

namespace Besnovatyj\Contracts\search;

/**
 * Источник индексируемого контента, объявляемый модулем-провайдером {@see SearchableProvider}.
 *
 * Описывает один вид контента модуля («статьи блога», «товары», «персоны») — то, что пользователь
 * видит на фронте как вкладку-фасет поисковой выдачи, а администратор — как строку в настройках
 * индексации. Нейтральный DTO без зависимостей — живёт в контрактах, чтобы и модуль-провайдер,
 * и модуль поиска могли ссылаться на него, не завися друг от друга.
 *
 * Один модуль вправе объявить несколько источников (блог — посты и таксономии), при этом каждый
 * источник индексируется, фильтруется и переиндексируется независимо от остальных.
 */
final readonly class SearchSource
{
    /**
     * @param string      $type  Стабильный ключ источника в формате `<модуль>.<сущность>`
     *                           (напр. `blog.post`, `shop.product`). ПОПАДАЕТ В БАЗУ индекса и в
     *                           query-параметры фронта, поэтому менять его после запуска нельзя —
     *                           смена ключа требует полной переиндексации.
     * @param string      $label Человекочитаемая подпись для фасета выдачи и настроек
     *                           (напр. «Статьи блога»).
     * @param float       $boost Множитель релевантности источника по умолчанию: >1 поднимает его
     *                           документы в общей выдаче, <1 опускает. Администратор может
     *                           переопределить значение в настройках модуля поиска.
     * @param string|null $icon  CSS-класс иконки для вкладки фасета (напр. `bi bi-newspaper`).
     *                           null — фасет рисуется без иконки.
     */
    public function __construct(
        public string $type,
        public string $label,
        public float $boost = 1.0,
        public ?string $icon = null,
    ) {
    }
}
