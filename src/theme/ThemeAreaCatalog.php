declare(strict_types=1);

namespace Besnovatyj\Contracts\theme;

/**
 * Каталог мест активной темы, которыми управляют из админки.
 *
 * Тема не может заводить свои CRUD в админке, поэтому она только ОБЪЯВЛЯЕТ места, а наполняет их
 * модуль блоков. Модуль зависит лишь от этого контракта: спрашивает список мест, чтобы показать
 * администратору, какие из них есть у активной темы, какие пусты и какие блоки лежат в местах,
 * которых тема больше не знает.
 *
 * Производитель списка — пакет тем (`yii2-cms-themes`), реализацию он связывает через DI. Нет пакета
 * тем — нет биндинга: модуль блоков работает со свободными идентификаторами мест.
 *
 * Инверсия зависимостей (DIP), как у {@see ViewVariantCatalog}: и тема, и модуль блоков зависят от
 * данной абстракции, а не друг от друга.
 */
interface ThemeAreaCatalog
{
    /**
     * Места активной темы в порядке отображения.
     *
     * @return array<string, ThemeArea> ключ — {@see ThemeArea::$id}
     */
    public function areas(): array;
}
