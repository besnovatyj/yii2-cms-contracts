declare(strict_types=1);

namespace Besnovatyj\Contracts\menu;

/**
 * Модуль объявляет свои цели для построения пунктов меню и доступные для них кандидаты (slug).
 *
 * Реализуется классом Yii-модуля (напр. {@see \Besnovatyj\Documents\Module}). Потребитель — модуль
 * меню: он находит провайдеров через `instanceof MenuTargetProvider` и строит каскад «модуль → цель →
 * кандидат» на отдельной странице админки, а затем создаёт пункт меню по выбранной цели и slug.
 *
 * Связанность нулевая: если модуля меню нет — контракт никто не вызывает; если модуль его не реализует —
 * он просто не появится в списке. Это применение принципа инверсии зависимостей (DIP): и провайдер, и
 * модуль меню зависят от данной абстракции, а не друг от друга.
 *
 * Дополняет виджет {@see \Besnovatyj\Menu\widgets\add\AddItemWidget}: виджет закрепляет произвольную
 * ссылку из контекста конкретной страницы, а этот контракт даёт централизованный каталог структурных
 * целей модуля без необходимости иметь страницу-носитель под виджет.
 */
interface MenuTargetProvider
{
    /**
     * Цели этого модуля, из которых можно строить пункты меню.
     *
     * @return MenuTarget[]
     */
    public function menuTargets(): array;

    /**
     * Доступные кандидаты (slug) для заданной цели — для выпадающего списка в админке.
     *
     * @param string $route роут цели (в том же виде, что в {@see MenuTarget::$route})
     * @return array<string,string> карта `slug => подпись` (напр. `'documents' => 'Документы'`)
     */
    public function menuCandidates(string $route): array;
}
