declare(strict_types=1);

namespace Besnovatyj\Contracts\sitemap;

/**
 * Модуль объявляет свой контент для карты сайта.
 *
 * Реализуется классом Yii-модуля (напр. {@see \Besnovatyj\Blog\Module}). Потребитель — модуль карты
 * сайта: он находит провайдеров через `instanceof SitemapProvider`, забирает у них адреса и
 * собирает XML-карту и HTML-карту. Связанность нулевая: нет модуля карты — контракт никто не
 * вызывает; не реализует модуль контракт — его страниц просто не будет в карте.
 *
 * Это применение принципа инверсии зависимостей (DIP): и провайдер, и модуль карты зависят от данной
 * абстракции, а не друг от друга. Провайдер при этом не знает ни про нарезку по файлам, ни про
 * лимиты протокола, ни про построение абсолютных URL — он отдаёт доменные данные, и только.
 *
 * Ответственность провайдера — фильтрация по публичности: в карту попадает РОВНО то, что анонимный
 * посетитель и так может открыть на фронте. Черновики, снятые с публикации записи и содержимое
 * скрытых разделов отдавать нельзя — карта публична, а адрес из неё поисковая система запомнит
 * надолго. Тот же инвариант, что у {@see \Besnovatyj\Contracts\search\SearchableProvider}: выборки
 * берутся из `readModels` (`visible()`), а не из репозиториев админки.
 *
 * Отдельный контракт, а не переиспользование поискового: карта не должна исчезать вместе с модулем
 * поиска, в неё обязаны попадать страницы без индексируемого текста (галереи, листинги, контакты), а
 * `lastmod` — это дата ИЗМЕНЕНИЯ, тогда как поисковый документ несёт дату публикации.
 *
 * @see SitemapSection  объявление раздела карты
 * @see SitemapUrl      единица карты
 * @see SitemapFreshness необязательное расширение для тяжёлых разделов
 */
interface SitemapProvider
{
    /**
     * Разделы карты, наполняемые этим модулем.
     *
     * @return SitemapSection[]
     */
    public function sitemapSections(): array;

    /**
     * Все публично доступные адреса указанного раздела.
     *
     * Вызывается из консоли и из админки, поэтому обязан быть экономным по памяти: возвращать
     * генератор (`yield`) и читать записи пачками (`batch()`/`each()` в Yii), а не собирать весь
     * массив целиком. Порядок важен только для HTML-карты — там адреса выводятся как отданы, что
     * позволяет отдать дерево разделов в порядке обхода вместе с {@see SitemapUrl::$depth}.
     *
     * Для неизвестного `$section` (раздел отключён, ключ устарел) следует вернуть пустой итератор, а
     * не бросать исключение — модуль карты опрашивает провайдеров пачкой.
     *
     * @param string $section ключ раздела из {@see SitemapSection::$key}
     * @return iterable<SitemapUrl>
     */
    public function sitemapUrls(string $section): iterable;
}
