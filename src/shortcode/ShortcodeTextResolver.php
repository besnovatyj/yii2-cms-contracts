declare(strict_types=1);

namespace Besnovatyj\Contracts\shortcode;

/**
 * Резолвер текстовых шорткодов вида `%name%` внутри произвольной строки.
 *
 * Узкая абстракция, позволяющая ядру и любому модулю развернуть текстовые шорткоды
 * (например, `%staticHost%`, `%homeUrl%`) в конкретные значения, НЕ завися от реализации
 * модуля шорткодов. Компонент приложения `shortcode` реализует этот интерфейс; потребитель
 * проверяет `instanceof ShortcodeTextResolver`, чем разрывается связанность потребитель → пакет
 * шорткодов и сохраняется его опциональность (модуль шорткодов не обязателен для минимальной
 * установки — при его отсутствии потребитель просто оставляет строку как есть).
 *
 * Это применение принципа инверсии зависимостей (DIP): и потребитель, и модуль шорткодов зависят
 * от данной абстракции, а не друг от друга.
 */
interface ShortcodeTextResolver
{
    /**
     * Развернуть текстовые шорткоды `%name%` в строке в их значения.
     *
     * Виджетные шорткоды (`[widget ...]`) НЕ обрабатываются — только текстовые подстановки.
     * Неизвестные шорткоды остаются в исходном виде.
     *
     * @param string $content входная строка (например, URL с `%staticHost%`)
     * @return string строка с развёрнутыми текстовыми шорткодами
     */
    public function resolveText(string $content): string;
}
