declare(strict_types=1);

namespace Besnovatyj\Contracts\search;

/**
 * Модуль объявляет свой контент для сквозного поиска по сайту.
 *
 * Реализуется классом Yii-модуля (напр. {@see \Besnovatyj\Blog\Module}). Потребитель — модуль
 * поиска: он находит провайдеров через `instanceof SearchableProvider`, забирает у них документы
 * и складывает в единый индекс. Связанность нулевая: если модуля поиска нет — контракт никто не
 * вызывает; если модуль его не реализует — он просто не попадёт в выдачу.
 *
 * Это применение принципа инверсии зависимостей (DIP): и провайдер, и модуль поиска зависят от
 * данной абстракции, а не друг от друга. Провайдер при этом ничего не знает ни о движке поиска
 * (TNTSearch, Manticore, ...), ни о структуре индекса — он отдаёт доменные данные, и только.
 *
 * Ответственность провайдера — фильтрация по публичности: в индекс сквозного поиска попадает
 * РОВНО то, что анонимный посетитель и так может открыть на фронте. Черновики, снятые с публикации
 * и отложенные записи отдавать нельзя — индекс общий и публичный.
 *
 * @see SearchSource   объявление вида контента
 * @see SearchDocument единица индексации
 */
interface SearchableProvider
{
    /**
     * Виды контента этого модуля, участвующие в сквозном поиске.
     *
     * @return SearchSource[]
     */
    public function searchSources(): array;

    /**
     * Все публично доступные документы указанного источника — для полной переиндексации.
     *
     * Вызывается из консоли и из админки, поэтому обязан быть экономным по памяти: возвращать
     * генератор (`yield`) и читать записи пачками (`batch()`/`each()` в Yii), а не собирать
     * весь массив целиком. Порядок документов не важен.
     *
     * Для неизвестного `$type` (источник отключён, ключ устарел) следует вернуть пустой итератор,
     * а не бросать исключение — модуль поиска опрашивает провайдеров пачкой.
     *
     * @param string $type ключ источника из {@see SearchSource::$type}
     * @return iterable<SearchDocument>
     */
    public function searchDocuments(string $type): iterable;
}
