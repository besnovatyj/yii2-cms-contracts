declare(strict_types=1);

namespace Besnovatyj\Contracts\upload;

/**
 * Модуль объявляет свои модели с превью изображений.
 *
 * Реализуется классом Yii-модуля. Потребитель — модуль загрузок: он находит провайдеров через
 * `ModuleFinder::implementing()` и по их источникам ставит в очередь сквозной прогрев или
 * перегенерацию превью (например, после очистки кеша статики или переезда на новый хостинг).
 * Связанность нулевая: нет модуля загрузок — контракт никто не вызывает; не реализует модуль
 * контракт — его превью просто не попадают в сквозной прогрев (прогрев на странице самого
 * модуля это не отменяет).
 *
 * Провайдер отдаёт только описание источников, без выборок: обход записей и постановка заданий —
 * забота модуля загрузок.
 *
 * @see ThumbnailSource описание одного источника
 */
interface ThumbnailSourceProvider
{
    /**
     * Модели модуля, у которых есть превью.
     *
     * @return ThumbnailSource[]
     */
    public function thumbnailSources(): array;
}
