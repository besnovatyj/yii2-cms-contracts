declare(strict_types=1);

namespace Besnovatyj\Contracts\snippet;

/**
 * Источник сниппетов для пикера WYSIWYG-редактора.
 *
 * Реализуется чем угодно, что может отдать заготовленные куски контента: модулем сниппетов
 * (из БД), любым другим модулем (свои структурные сниппеты), конфигом. Потребитель — модуль-
 * агрегатор сниппетов: он находит провайдеров (напр. через `instanceof SnippetProvider` по
 * подключённым модулям) и склеивает их группы в единое дерево, которое отдаёт фронту API-эндпоинтом.
 *
 * Связанность нулевая: нет агрегатора — контракт никто не вызывает; модуль его не реализует —
 * он просто не появится в дереве. Это инверсия зависимостей (DIP), в точности как у
 * {@see \Besnovatyj\Contracts\menu\MenuTargetProvider}: и провайдер, и агрегатор зависят от этой
 * абстракции, а не друг от друга, поэтому источники сниппетов остаются подключаемыми плагинами.
 */
interface SnippetProvider
{
    /**
     * Категории сниппетов этого источника.
     *
     * @return SnippetGroup[]
     */
    public function snippetGroups(): array;
}
