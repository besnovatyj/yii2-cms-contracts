declare(strict_types=1);

namespace Besnovatyj\Contracts\config;

/**
 * Поставщик вариантов выбора для опции модуля настроек.
 *
 * Нужен там, где список вариантов — это НЕ перечисление режимов («обрезать / вписывать»,
 * «да / нет»), а состав системы: установленные ядра поиска, движки редактора, темы. Такой список
 * система знает сама, и записанная в `options.php` копия неизбежно расходится с правдой: поставили
 * ещё один пакет — надо не забыть дописать вариант, выключили модуль в менеджере — вариант всё
 * равно предлагается.
 *
 * Почему не собрать список прямо в `options.php`: этот файл читается не только в рантайме.
 * Менеджер модулей считает от объявленных опций контрольную сумму манифеста, и модуль с «плавающим»
 * списком помечался бы как изменившийся при каждой установке соседнего пакета. Поэтому объявление
 * остаётся статичным — меняется лишь ОДНА строка: вместо готового массива указывается класс,
 * который соберёт список тогда, когда приложение уже поднято.
 *
 * Реализация получается из DI-контейнера, поэтому может свободно зависеть от сервисов своего
 * модуля (реестра, каталога) — обычным внедрением через конструктор.
 *
 * Объявление опции:
 * ```php
 * 'inputOptions' => [
 *     'type'          => 'dropdown',
 *     'itemsProvider' => \Besnovatyj\Search\settings\EngineOptionItems::class,
 * ],
 * ```
 *
 * Список одновременно служит и правилом валидации: сохранить значение вне набора ключей нельзя,
 * отдельное правило `['in', 'range' => ...]` для этого писать не нужно (и не следует — второй
 * список рассинхронизируется с первым).
 */
interface OptionItemsProvider
{
    /**
     * Варианты выбора: сохраняемое значение => подпись для администратора.
     *
     * Вызывается при отрисовке страницы настроек и при сохранении значения. Пустой массив —
     * допустимый ответ (например, не установлено ни одного подходящего пакета): поле окажется
     * пустым, а сохранить в него будет нечего.
     *
     * @return array<string, string>
     */
    public function items(): array;
}
