namespace Besnovatyj\Contracts\theme;

/**
 * Каталог вариантов представления, предоставляемых активной темой.
 *
 * Узкая абстракция «выбираемый шаблон представления». Любой модуль-потребитель (Page, Blog, …)
 * зависит ТОЛЬКО от этого контракта: спрашивает, какие варианты доступны для его «слота»
 * (точки выбора вида `{moduleId}:{путь-view}`), и валиден ли сохранённый в БД ключ. Ни имени
 * темы, ни файловой системы, ни пакета тем потребитель не касается.
 *
 * Производитель списка — пакет тем (`yii2-cms-themes`), который сканирует оверлеи активной темы
 * и генерирует артефакт, а реализацию каталога связывает через DI. Если пакет тем не установлен,
 * биндинг отсутствует — потребитель мягко откатывается к базовому представлению (пустой каталог).
 *
 * Это применение принципа инверсии зависимостей (DIP): и потребитель, и пакет тем зависят от данной
 * абстракции, а не друг от друга. Ср. {@see LayoutPathProvider} и {@see ViewSourcesManifest}.
 *
 * Формат слота и файловая конвенция вариантов задаются в {@see ViewVariantsManifest}.
 */
interface ViewVariantCatalog
{
    /**
     * Доступные варианты для слота: `ключ-варианта => человекочитаемое имя`.
     *
     * Ключ — имя файла варианта без расширения (`landing`, `raw`), имя — метка из `_labels.php`
     * темы (или сам ключ, если метки нет). Пустой массив — тема не предлагает вариантов для слота.
     *
     * @param string $slot идентификатор точки выбора, напр. `Page:frontend/page/view`
     * @return array<string,string>
     */
    public function getVariants(string $slot): array;

    /**
     * Есть ли у слота указанный вариант в активной теме.
     *
     * Потребитель обязан проверять этим методом сохранённый в БД ключ перед рендером: тема могла
     * его удалить/переименовать, тогда рендерить базовое представление.
     *
     * @param string $slot    идентификатор точки выбора
     * @param string $variant ключ варианта
     */
    public function hasVariant(string $slot, string $variant): bool;
}
