declare(strict_types=1);

namespace Besnovatyj\Contracts\tags;

/**
 * Модуль объявляет свой контент участником общей системы тегов.
 *
 * Реализуется классом Yii-модуля (напр. `Besnovatyj\Blog\Module`). Потребитель — модуль тегов
 * (`yii2-cms-tags`): он находит провайдеров через `instanceof TaggableProvider`, как это делают
 * поиск и карта сайта, и через них собирает страницу тега `/tag/<slug>` и облако тегов.
 *
 * Разделение ответственности:
 *  - модуль тегов владеет словарём тегов и таблицей связей `tags_assignments(tag_id, entity_type,
 *    entity_id)` — полиморфной, без внешнего ключа на таблицу сущности (таблиц много, они в разных
 *    модулях), поэтому ни одной сущности он сам прочитать не может;
 *  - контентный модуль — единственный, кто знает, какие его записи видимы анониму и как выглядит
 *    карточка записи. Именно это он и отдаёт через два метода ниже. Черновики и снятые с публикации
 *    записи провайдер обязан отфильтровать сам: страница тега общая и публичная.
 *
 * Ключ типа `type` (`blog.post`) — тот же, что в контрактах поиска, карты сайта и меню: одна сущность
 * адресуется одним ключом во всех сквозных модулях.
 *
 * @see TagSource  объявление вида контента
 * @see TaggedItem карточка записи для страницы тега
 */
interface TaggableProvider
{
    /**
     * Виды контента этого модуля, к которым можно привязывать теги.
     *
     * @return TagSource[]
     */
    public function tagSources(): array;

    /**
     * Из переданных идентификаторов — те, чьи записи анонимный посетитель может открыть на фронте.
     *
     * Используется для счётчиков на странице тега и в облаке: тег, все записи которого скрыты,
     * не должен вести на пустую страницу и выдавать существование скрытого контента. Порядок
     * результата не важен; для неизвестного `$type` — пустой массив.
     *
     * @param string $type ключ источника из {@see TagSource::$type}
     * @param int[]  $ids  идентификаторы записей этого типа
     * @return int[]
     */
    public function visibleTaggedIds(string $type, array $ids): array;

    /**
     * Карточки записей для страницы тега — только видимые анониму, в порядке переданных `$ids`.
     *
     * Вызывается уже для страницы выдачи (десятки id, не тысячи), поэтому может грузить сущности
     * целиком вместе с превью. Для неизвестного `$type` — пустой итератор, не исключение.
     *
     * @param string $type ключ источника из {@see TagSource::$type}
     * @param int[]  $ids  идентификаторы записей этого типа
     * @return iterable<TaggedItem>
     */
    public function taggedItems(string $type, array $ids): iterable;
}
