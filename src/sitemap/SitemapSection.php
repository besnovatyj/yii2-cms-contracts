declare(strict_types=1);

namespace Besnovatyj\Contracts\sitemap;

/**
 * Раздел карты сайта, объявляемый модулем-провайдером {@see SitemapProvider}.
 *
 * Описывает один вид контента модуля («статьи блога», «разделы блога», «страницы») — то, что
 * администратор видит строкой в настройках карты, а посетитель — блоком HTML-карты. Нейтральный DTO
 * без зависимостей, живёт в контрактах, чтобы и модуль-провайдер, и модуль карты могли ссылаться на
 * него, не завися друг от друга. Прямой аналог {@see \Besnovatyj\Contracts\search\SearchSource}.
 *
 * Раздел — ещё и единица нарезки: каждый попадает в собственный файл `sitemap-<ключ>-<N>.xml`
 * (при переполнении — в несколько), поэтому крупную сущность стоит объявлять отдельным разделом, а
 * не подмешивать к соседней: так переобход одного раздела не заставляет краулера перечитывать всё.
 */
final readonly class SitemapSection
{
    /**
     * @param string          $key             Стабильный ключ раздела в формате `<модуль>.<сущность>`
     *                                         (`blog.post`, `page.page`). Попадает в ИМЯ ФАЙЛА карты
     *                                         (точка заменяется дефисом) и в настройки администратора,
     *                                         поэтому менять его после запуска не следует: краулеры
     *                                         помнят прежние адреса, а сохранённые переопределения
     *                                         приоритета «отвяжутся».
     * @param string          $label           Человекочитаемая подпись: заголовок блока в HTML-карте и
     *                                         строка в админке (напр. «Статьи блога»).
     * @param ChangeFrequency $changeFrequency Частота изменения по умолчанию для всех адресов раздела;
     *                                         отдельный адрес вправе её переопределить.
     * @param float           $priority        Относительный вес раздела внутри сайта, 0.0…1.0. Значение
     *                                         сравнивается только с другими адресами ЭТОГО сайта —
     *                                         поставить всему сайту 1.0 равносильно тому, чтобы не
     *                                         ставить ничего.
     * @param bool            $inHtmlMap       Показывать ли раздел на HTML-карте. `false` — раздел
     *                                         нужен роботам, но не человеку (напр. страницы пагинации).
     * @param int            $order            Порядок блока на HTML-карте: меньше — выше.
     * @param string|null    $icon             CSS-класс иконки заголовка блока (напр. `bi bi-newspaper`).
     *                                         null — блок рисуется без иконки.
     */
    public function __construct(
        public string $key,
        public string $label,
        public ChangeFrequency $changeFrequency = ChangeFrequency::Weekly,
        public float $priority = 0.5,
        public bool $inHtmlMap = true,
        public int $order = 100,
        public ?string $icon = null,
    ) {
    }
}
