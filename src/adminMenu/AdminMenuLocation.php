declare(strict_types=1);

namespace Besnovatyj\Contracts\adminMenu;

/**
 * Локация меню админки — место интерфейса, в которое модуль ставит свой пункт ({@see AdminMenuPlacement}).
 *
 * Единственный список локаций. Перечисление, а не строки: опечатка в имени локации ловится IDE и
 * автозагрузкой, а не превращается в молча пропавший пункт меню. Новая локация появляется здесь и
 * только вместе с тем, кто её показывает.
 *
 * Значение — стабильный строковый идентификатор локации (ключ раскладки, сериализация для клиента).
 */
enum AdminMenuLocation: string
{
    /** Основная навигация: разделы контента и модулей. Показывает левый сайдбар layout'а админки. */
    case LeftSidebar = 'left-sidebar';

    /** Служебные разделы: настройки и системные инструменты. Показывает правый сайдбар layout'а админки. */
    case RightSidebar = 'right-sidebar';

    /** Кнопки быстрых действий в шапке админки. Показывает модуль admin-panel. */
    case HeaderQuickLinks = 'header-quick-links';
}
